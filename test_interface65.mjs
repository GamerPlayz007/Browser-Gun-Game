import assert from 'node:assert/strict';
import fs from 'node:fs';
import {ROOM_CODES65,validRoom65,kd65,radarType65,roomLabel65} from './static/interface65.js';
assert.deepEqual(ROOM_CODES65.slice(0,3),['MAX','ACE','FOX']);
assert.equal(ROOM_CODES65.length,12);
assert.equal(new Set(ROOM_CODES65).size,12);
assert.ok(ROOM_CODES65.every(v=>/^[A-Z]{3,4}$/.test(v)));
assert.equal(validRoom65('max'),true);
assert.equal(validRoom65('HACK'),false);
assert.equal(kd65(12,5),'2.40');
assert.equal(kd65(6,0),'6.00');
assert.equal(kd65(0,0),'0.00');
const me={id:'me',hp:200,x:0,z:0,team:'azure'};
const pal={id:'pal',hp:200,x:3,z:2,team:'azure'};
const foe={id:'foe',hp:200,x:5,z:4,team:'ember'};
assert.equal(radarType65(me,{meId:'me',team:'azure',mode:'teamdeathmatch'}),null);
assert.equal(radarType65(pal,{meId:'me',team:'azure',mode:'teamdeathmatch'}),'ally');
assert.equal(radarType65(foe,{meId:'me',team:'azure',mode:'teamdeathmatch'}),'enemy');
assert.equal(radarType65(pal,{meId:'me',mode:'deathmatch'}),'enemy');
assert.equal(radarType65(pal,{meId:'me',mode:'botmatch'}),'ally');
assert.equal(radarType65({...foe,id:'bot',bot:true},{meId:'me',mode:'botmatch'}),'enemy');
assert.equal(radarType65({...foe,hp:0},{meId:'me',mode:'deathmatch'}),null);
assert.equal(radarType65({...foe,x:NaN},{meId:'me',mode:'deathmatch'}),null);
assert.equal(roomLabel65({code:'MAX',players:0,active:false}),'MAX · EMPTY');
assert.equal(roomLabel65({code:'ACE',players:3,max:8,active:true}),'ACE · 3/8 players');
const html=fs.readFileSync('./static/index.html','utf8');
const game=fs.readFileSync('./static/game.js','utf8');
const mini=fs.readFileSync('./static/minimap.js','utf8');
for(const id of ['kills65','deaths65','kd65','manual-respawn65','code']){
 assert.ok(html.includes('id="'+id+'"'),'Missing UI '+id);
}
