import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from 'three';
import {createCyberMaterialLibrary} from './static/materials41.js';
import {createUrbanDetails67,URBAN_QUALITY67} from './static/urban67.js';
import {makePlayer,makeWeapon,setModelQuality67,animatePlayer,animateWeapon,disposePlayer} from './static/models.js';
import {avatarPose} from './static/animation34.js';
const ctx=new Proxy({}, {get:()=>()=>{}});
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>ctx})};
const map=JSON.parse(fs.readFileSync('static/map.json','utf8'));
assert.equal(map.daybreak67.revision,'06.7');
assert.equal(map.daybreak67.furnishings.length,map.boxes.filter(x=>x.daybreak67Physical).length);
assert.equal(Object.keys(URBAN_QUALITY67).length,5);
const lib=createCyberMaterialLibrary(T);
const layer=createUrbanDetails67(T,map,lib);
const {stats,root}=layer;
assert.ok(stats.streetFurniture>=16);
assert.ok(stats.shops>=18);
assert.ok(stats.parts>=stats.streetFurniture*2);
assert.ok(stats.batches<=35,'Stay within school iGPU static instancing budget');
assert.ok(stats.signBatches<=2);
assert.ok(root.children.every(x=>x.userData.collidable===false));
assert.ok(root.children.some(x=>x.isInstancedMesh));
assert.ok(root.children.every(x=>x.isInstancedMesh||x.isMesh));
layer.setQuality('performance');
const perf=root.children.filter(x=>x.visible).length;
layer.setQuality('auto');
const normal=root.children.filter(x=>x.visible).length;
layer.setQuality('ultra');
const ultra=root.children.filter(x=>x.visible).length;
assert.ok(perf<normal&&normal<ultra);
layer.setQuality('auto');layer.setDetail(false);
assert.equal(root.children.filter(x=>x.visible).length,perf);
layer.setDetail(true);
assert.equal(root.children.filter(x=>x.visible).length,normal);
const scene=new T.Scene();scene.add(root);
layer.dispose();assert.equal(scene.children.length,0);
lib.dispose();
const gun=makeWeapon(2),p=makePlayer('Daybreak Player');
const extras=o=>{const array=[];o.traverse(n=>{if(Number.isInteger(n.userData.detailTier67))array.push(n);});return array;};
assert.ok(extras(p).length>=5);
assert.ok(extras(gun).length>=2);
setModelQuality67(p,'performance');
setModelQuality67(gun,'performance');
assert.ok(extras(p).every(n=>!n.visible));
assert.ok(extras(gun).every(n=>!n.visible));
setModelQuality67(p,'high');
assert.ok(extras(p).some(n=>n.visible));
assert.ok(extras(p).some(n=>!n.visible));
setModelQuality67(p,'ultra');
assert.ok(extras(p).every(n=>n.visible));
setModelQuality67(gun,'ultra');
assert.ok(extras(gun).every(n=>n.visible));
animateWeapon(gun,{time:4,ads:0,reload:0,kick:.12,moving:true,slide:0,motion:true,switched:0});
const pose=avatarPose({vx:0,vz:0,yaw:0,grounded:true},.5);
assert.ok(Number.isFinite(pose.idleBreath)&&Number.isFinite(pose.hipYaw));
for(let n=0;n<120;n++){
 const time=n/60;
 const pstate={vx:n%2?8:1.5,vz:0,yaw:0,grounded:true,
   crouch:n%11===0,slide:0,spawn:1};
 const result=animatePlayer(p,pstate,time);
 for(const k of ['hipYaw','idleBreath','legSide','armWeight'])
  assert.ok(Number.isFinite(result[k]),'Bad pose '+k);
}
disposePlayer(p);
console.log('Daybreak 6.7: safe urban cover, batched outer-city details, adaptive quality, player and weapon rigs passed.');
