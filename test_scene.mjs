import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import {buildWorld} from './static/world.js';
import {makeWeapon,makePlayer,animateWeapon,animatePlayer} from './static/models.js';
import {simulate} from './static/physics.js';
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>({fillRect(){},strokeRect(){},fillText(){}})})};
const map=JSON.parse(fs.readFileSync('static/map.json'));
const scene=new THREE.Scene();const world=buildWorld(scene,map);
let meshes=0,triangles=0;
scene.traverse(o=>{if(!o.isMesh)return;meshes++;const p=o.geometry.attributes.position;assert.ok(p, 'position attribute');for(const value of p.array)assert.ok(Number.isFinite(value));triangles+=(o.geometry.index?.count||p.count)/3;});
assert.ok(meshes<35,`Static scene batching: ${meshes}`);assert.ok(triangles<18000,`City triangle budget: ${triangles}`);assert.equal(world.targets.size,2);
assert.ok(world.staticBatches<=20,`Static batch budget: ${world.staticBatches}`);
assert.equal(new Set(scene.children[0].children.filter(o=>o.isMesh&&o.userData.zone).map(o=>o.userData.zone)).size,4);
assert.ok(!scene.children.some(o=>o.isPointLight));
console.log(`World: ${world.staticBatches} static batches across four zones`);
for(let id=0;id<4;id++){const gun=makeWeapon(id);assert.equal(gun.userData.id,id);for(const reload of [0,.25,.5,.9])animateWeapon(gun,{time:1,ads:1,reload,kick:.02,moving:true,slide:0,motion:true,switched:0});}
const player=makePlayer('Test');animatePlayer(player,{vx:5,vz:0,crouch:false,pitch:0,yaw:0},1);
const p={x:-29,y:1,z:14,vx:0,vy:0,vz:0,yaw:0,grounded:true,slide_until:0,slide_ready:0,jump_held:false,slide_held:false};
for(let i=0;i<105;i++)simulate(p,{w:true},1/30,100+i/30,map.boxes,map.weapons[0]);
assert.equal(p.y,5);assert.ok(p.z<-2);console.log(`Scene checks passed: ${meshes} meshes, ${Math.round(triangles)} triangles. Client stairs, rig and four weapon animations passed.`);
