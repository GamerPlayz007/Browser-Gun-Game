import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from 'three';
import {buildWorld} from './static/world.js';
import {createCyberMaterialLibrary,MATERIAL_ATLAS_SIZE68} from './static/materials41.js';
import {AutoQuality,renderRatio} from './static/display.js';

const ctx=new Proxy({}, {get:()=>()=>{}});
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>ctx})};
const map=JSON.parse(fs.readFileSync('static/map.json','utf8'));
const baseline=map.boxes.map(b=>JSON.stringify(b));
const low=createCyberMaterialLibrary(T,{initialQuality:'performance'});
const road=low.get('road'),window=low.get('window');
assert.equal(MATERIAL_ATLAS_SIZE68.performance,256);
assert.equal(MATERIAL_ATLAS_SIZE68.auto,256);
assert.equal(MATERIAL_ATLAS_SIZE68.ultra,512);
assert.equal(low.atlasSize68,256);
assert.equal(road.map.image.width,256);
assert.equal(window.map.image.height,256);
assert.equal(road.bumpMap,null);
assert.equal(road.emissiveMap,null);
const lowMap=road.map;
assert.equal(low.setQuality('performance'),false);
assert.equal(low.textureRebuilds68,0);
assert.equal(low.setQuality('auto'),true);
assert.equal(low.textureRebuilds68,0,'School to Auto retains 256px atlases');
assert.ok(road.bumpMap,'Auto restores bump channel when headroom permits');
assert.equal(low.setQuality('ultra'),true);
assert.equal(low.atlasSize68,512);
assert.equal(road.map.image.width,512);
assert.notStrictEqual(road.map,lowMap);
assert.equal(low.textureRebuilds68,1);
assert.equal(low.setQuality('ultra'),false);
assert.equal(low.textureRebuilds68,1,'Repeated Ultra must not recompile or regenerate');
assert.equal(low.setQuality('performance'),true);
assert.equal(low.atlasSize68,256);
assert.equal(low.textureRebuilds68,2,'School reclaims 512px materials');
assert.equal(road.bumpMap,null);
low.dispose();

const scene=new T.Scene();
const world=buildWorld(scene,map,{quality:'performance'});
assert.equal(world.resourceProfile68.atlasSize,256);
assert.equal(world.resourceProfile68.hasEnvironment,false);
assert.equal(world.resourceProfile68.fullArchitecture,false);
assert.ok(world.resourceProfile68.stage5Meshes>0,'Tier-0 architecture stays visible');
assert.ok(world.resourceProfile68.stage6Meshes>0,'Tier-0 skyline stays visible');
const before=world.resourceProfile68;
world.setQuality('performance');
assert.equal(world.resourceProfile68.atlasRebuilds,before.atlasRebuilds);
world.setQuality('high');
assert.equal(world.resourceProfile68.fullArchitecture,true);
assert.equal(world.resourceProfile68.atlasSize,512);
assert.ok(world.resourceProfile68.stage5Meshes>before.stage5Meshes);
assert.ok(world.resourceProfile68.stage6Meshes>before.stage6Meshes);
const count=world.resourceProfile68.stage5Meshes+world.resourceProfile68.stage6Meshes;
const textures=world.resourceProfile68.atlasRebuilds;
world.setQuality('high');
assert.equal(world.resourceProfile68.atlasRebuilds,textures);
assert.equal(world.resourceProfile68.stage5Meshes+world.resourceProfile68.stage6Meshes,count);
world.setQuality('performance');
assert.equal(world.resourceProfile68.atlasSize,256);
assert.equal(world.resourceProfile68.hasEnvironment,false);
world.dispose();
assert.equal(scene.children.length,0);
assert.deepEqual(map.boxes.map(b=>JSON.stringify(b)),baseline,'Rendering cannot mutate multiplayer colliders');

const meter=new AutoQuality('auto');
const sample=(n,ms)=>{for(let i=0;i<n;i++)meter.sample(ms);};
sample(120,16);
sample(180,145);
assert.ok(meter.scale<1,'Auto must downgrade even when actual frames exceed 100ms');
assert.equal(renderRatio(1920,1080,2,'performance'),.5);
const html=fs.readFileSync('static/index.html','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const lock=JSON.parse(fs.readFileSync('package-lock.json','utf8'));
assert.equal(pkg.version,'3.1.0');
assert.equal(lock.version,'3.1.0');
assert.equal(lock.packages[''].version,'3.1.0');
assert.ok(html.includes('<sup>V3.1 DAYBREAK</sup>'));
assert.ok(html.includes('sunlit streets'));
assert.ok(!html.includes('120m of neon streets'));
const game=fs.readFileSync('static/game.js','utf8');
assert.ok(game.includes('if(document.hidden){fpsFrames=0;fpsLast=ms;movementAccumulator=0;return;}'));
console.log('v3.1: 256px School textures, 512px Ultra recovery, lazy skyline, stable geometry, slow-frame scaling, release badges passed.');
