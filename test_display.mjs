import assert from 'node:assert/strict';
import {AutoQuality,displaySize,renderRatio,createDisplay,QUALITY_MODES,RESOLUTION_CAPS} from './static/display.js';
for(const [w,h,dpr] of [[1366,768,1],[1920,1080,1],[1536,864,1.25],[1920,1080,2],[2560,1440,2]]){
 const size=displaySize(w,h,dpr);assert.equal(size.width,Math.round(w*dpr));assert.equal(size.height,Math.round(h*dpr));
}
assert.equal(displaySize(10000,8000,3,1,16384).width,16384);
assert.deepEqual(QUALITY_MODES,['auto','performance','high','ultra','native']);
assert.deepEqual(RESOLUTION_CAPS.performance,{width:960,height:540});
assert.equal(renderRatio(1920,1080,2,'performance'),.5,'School must draw only 960×540 at 1080p');
assert.equal(renderRatio(1920,1080,2,'auto'),2/3,'Auto must start at 1280×720');
assert.equal(renderRatio(1366,768,1,'performance'),960/1366);
assert.equal(renderRatio(1920,1080,2,'high'),2,'Manual High may use native DPI');
assert.ok(Math.abs(renderRatio(1920,1080,2,'auto',.6)-.4)<1e-9,'Auto may shrink under load');
const q=new AutoQuality('auto'),frames=(n,ms,dpr=2,visible=true)=>{for(let i=0;i<n;i++)q.sample(ms,dpr,visible);};
assert.equal(q.detail,false,'Auto must begin on reduced visual effects');
frames(120,16);frames(180,25);assert.equal(q.scale,.9,'Slow hardware should reduce framebuffer resolution');
frames(3000,25);assert.ok(q.scale>=.6&&q.scale<=.9,'Auto must have a safe dynamic resolution floor');
frames(10000,10);assert.equal(q.scale,1);assert.equal(q.detail,true,'Auto can recover visual effects after sustained fast frames');
q.setMode('high');frames(3000,40);assert.equal(q.detail,true);assert.equal(q.scale,1);
q.setMode('performance');frames(3000,40);assert.equal(q.detail,false);assert.equal(q.scale,1);
q.setMode('ultra');assert.equal(q.detail,true);
q.setMode('auto');frames(1000,90,2,false);assert.equal(q.scale,1);assert.equal(q.detail,false);
let detail=true,ratio=0,resizes=0;
globalThis.window={innerWidth:1920,innerHeight:1080,devicePixelRatio:2};globalThis.document={hidden:false};
const renderer={getContext:()=>({MAX_RENDERBUFFER_SIZE:1,getParameter:()=>16384}),setPixelRatio:r=>ratio=r,setSize:()=>resizes++};
const camera={updateProjectionMatrix(){}};const display=createDisplay(renderer,[camera],d=>detail=d,'high');
assert.equal(ratio,2);display.frame(16);assert.equal(resizes,1);
display.setMode('performance');assert.equal(ratio,.5);assert.equal(display.buffer.width,960);assert.equal(display.buffer.height,540);assert.equal(detail,false);
display.setMode('ultra');assert.equal(ratio,2);assert.equal(detail,true);
window.innerWidth=1280;window.innerHeight=720;display.resize();assert.equal(display.buffer.width,2560);assert.equal(camera.aspect,1280/720);
window.devicePixelRatio=1.25;display.frame(16);assert.equal(ratio,1.25);
display.setMode('auto');assert.equal(detail,false);assert.ok(ratio<=1+1e-6);
window.devicePixelRatio=3;display.resize();assert.ok(ratio<=1+1e-6,'Auto must cap HiDPI render cost');
window.innerWidth=1920;window.innerHeight=1080;display.resize();assert.equal(display.buffer.width,1280);
assert.equal(display.buffer.height,720);assert.ok(display.label().includes('1280×720'));
display.setMode('native');assert.equal(ratio,3,'Native still permits full HiDPI');
