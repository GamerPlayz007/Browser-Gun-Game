"""Verbatim triangle-mesh collider reader for Dust Corridor's server side.

Stage 6.3 conversion contract, not wired into live server movement yet.
Generated by node scripts/export_dust_collision63.mjs.

Format: 8-byte magic DUSTCOL3, uint32 LE count, count*9 float32 LE
vertex positions, count uint8 surface/material codes, all gzip-compressed.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import gzip
import hashlib
import json
import struct


@dataclass(frozen=True)
class DustCollider63:
    count: int
    vertices: bytes
    surfaces: bytes
    metadata: dict

    def triangle(self, index):
        if not 0 <= index < self.count:
            raise IndexError(index)
        return struct.unpack_from('<9f', self.vertices, index*36)

    def surface(self, index):
        if not 0 <= index < self.count:
            raise IndexError(index)
        return self.surfaces[index]


def load_dust_collision63(folder=None):
    root = Path(folder) if folder is not None else Path(__file__).parent / 'static' / 'maps'
    meta = json.loads((root/'dust_collision63.meta.json').read_text(encoding='utf-8'))
    raw = gzip.decompress((root/'dust_collision63.bin.gz').read_bytes())
    if raw[:8] != b'DUSTCOL3':
        raise ValueError('Unrecognized Dust Corridor collision format')
    if len(raw) < 12:
        raise ValueError('Truncated collision header')
    (count,) = struct.unpack_from('<I', raw, 8)
    if count < 1000 or count > 1000000 or count != meta['triangleCount']:
        raise ValueError('Collision metadata disagrees with geometry')
    if len(raw) != 12 + count*37:
        raise ValueError('Incorrect collision payload size')
    if hashlib.sha256(raw).hexdigest() != meta['rawSha256']:
        raise ValueError('Collision payload checksum mismatch')
    index = 12 + count*36
    return DustCollider63(count,raw[12:index],raw[index:],meta)
