import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {readAssetBytes,chooseGalleryFinish,chooseGalleryProfile} from '../static/gallery-assets.js';
import {showGalleryFallback} from '../static/gallery-bootstrap.js';

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const html=read('static/aether9-pbr-showroom.html');
const viewer=read('static/aether9-pbr-showroom.js');
const home=read('static/index.html');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length);
assert.ok([...viewer.matchAll(/\$\('([^']+)'\)/g)].every(m=>ids.includes(m[1])));
assert.ok(html.includes('/static/gallery-bootstrap.js'));
assert.ok(!home.includes('/static/aether-armory.html')); // obsolete W12/L7 overlays removed from game
assert.ok(html.includes('tabindex="0"'));
const elements=new Map();
const el=id=>{if(!elements.has(id))elements.set(id,{disabled:false,hidden:false,textContent:'',classList:{add(){}}});return elements.get(id)};
showGalleryFallback({getElementById:el});
assert.ok(el('canvas').hidden&&el('loading').hidden);
assert.ok(el('load-preferred').disabled&&el('quality').disabled&&el('file').disabled);
assert.match(el('status').textContent,/STATIC GALLERY REMAINS AVAILABLE/);
assert.equal(chooseGalleryFinish('invalid'),'midnight');
assert.equal(chooseGalleryProfile('performance',new Set(['original'])),'original');
assert.equal(chooseGalleryProfile('balanced',new Set(['original','balanced'])),'balanced');
const response=(parts,length=0)=>{let i=0;return {ok:true,headers:{get:()=>String(length)},body:{getReader:()=>({read:async()=>i<parts.length?{done:false,value:new Uint8Array(parts[i++])}:{done:true},cancel:async()=>{},releaseLock:()=>{}}),cancel:async()=>{}}}};
assert.deepEqual([...new Uint8Array(await readAssetBytes('/fixture',{maxBytes:8,fetchImpl:async()=>response([[1,2],[3]],3)}))],[1,2,3]);
await assert.rejects(readAssetBytes('/fixture',{maxBytes:3,fetchImpl:async()=>response([[1,2]],100)}),/budget/);
await assert.rejects(readAssetBytes('/fixture',{maxBytes:3,fetchImpl:async()=>response([[1,2],[3,4]],0)}),/budget/);
await assert.rejects(readAssetBytes('/fixture',{fetchImpl:async()=>({ok:false,status:404})}),/404/);
console.log('Gallery release regression fixtures passed');
