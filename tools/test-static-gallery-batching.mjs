import assert from 'node:assert/strict';
import * as T from 'three';
import {batchStaticScene} from '../static/static-gallery-batching.js';

const root=new T.Group();
root.position.set(2,3,4);
const material=new T.MeshStandardMaterial();
const glass=new T.MeshStandardMaterial({transparent:true,opacity:.5});
const shared=new T.BoxGeometry(1,1,1);
// Match a single-material glTF primitive rather than BoxGeometry's six material groups.
shared.clearGroups();
const parent=new T.Group();parent.position.set(2,0,0);root.add(parent);
const a=new T.Mesh(shared,material);a.position.set(1,0,0);parent.add(a);
const b=new T.Mesh(shared,material);b.position.set(-3,0,0);root.add(b);
const c=new T.Mesh(shared,glass);c.position.set(0,2,0);root.add(c);
const mirrored=new T.Mesh(shared,material);mirrored.scale.x=-1;root.add(mirrored);
const hidden=new T.Group();hidden.visible=false;root.add(hidden);
hidden.add(new T.Mesh(shared,material));
root.updateMatrixWorld(true);
const bounds=new T.Box3().setFromObject(root);
const triangles=o=>{let n=0;o.traverse(x=>{if(x.isMesh)n+=(x.geometry.index?.count??x.geometry.attributes.position.count)/3});return n};
const beforeTriangles=triangles(root);
const report=batchStaticScene(root);
assert.deepEqual(report,{before:5,after:4,batches:1,removed:1});
assert.equal(triangles(root),beforeTriangles);
assert.equal(c.parent,root);
assert.equal(mirrored.parent,root);
assert.equal(hidden.children.length,1);
const after=new T.Box3().setFromObject(root);
assert.ok(bounds.min.distanceTo(after.min)<1e-6);
assert.ok(bounds.max.distanceTo(after.max)<1e-6);
const again=batchStaticScene(root,{animated:true});
assert.equal(again.removed,0);
assert.equal(again.before,again.after);
const empty=batchStaticScene(new T.Group());
assert.equal(empty.before,0);
console.log('Static gallery batching fixture passed',report);
