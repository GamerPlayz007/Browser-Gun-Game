import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {WORKSHOP_CATALOG} from '../static/workshop-library.js';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const page=read('../static/workshop.html');
const workshop=read('../static/workshop.js');
const racks=read('../static/workshop-wall-racks.js');
const inspector=read('../static/workshop-component-inspector.js');
for(const id of ['modeWall','mode360','modeParts','partTools','spread','spreadValue','partSearch','partList','partDetails','partsCount','partReset','focusPart','selectedTitle','selectedMeta','savedImports','importAsset','file'])assert.ok(page.includes('id="'+id+'"'),'Missing: '+id);
assert.equal((page.match(/id="importAsset"/g)||[]).length,1,'Import should appear only once');
assert.ok(!page.includes('id="assetCards"'),'Weapon catalog should not clutter sidebar');
assert.ok(!page.includes('GET OFFICIAL SOURCE GLB'),'Lantern promotion should be removed');
assert.ok(!page.includes('IMPORT ANOTHER BLENDER GLB'),'Duplicate import control');
assert.ok(!page.includes('id="assetSearch"'),'No weapon list/filter in sidebar');
assert.ok(page.includes('<details id="advanced">'),'Secondary diagnostics should be collapsed');
assert.ok(workshop.includes("from './workshop-wall-racks.js'"));
assert.ok(workshop.includes("from './workshop-component-inspector.js'"));
assert.ok(workshop.includes('gallery.pick(camera,canvas'),'Wall rack pointer picking');
assert.ok(workshop.includes("inspector.setSpread("),'Exploded view spread');
assert.ok(workshop.includes('inspector.pick(camera,canvas'),'Click-to-select individual 3D meshes');
assert.ok(workshop.includes('renderPartList()'),'Individual mesh list');
assert.ok(workshop.includes("savedImports"),'Personal saved files remain accessible');
assert.ok(racks.includes('loader.parseAsync('),'Wall art must be GLB meshes, not JS placeholders');
assert.ok(racks.includes('raycaster.intersectObjects('),'3D raycast must select wall art');
const entries=[...racks.matchAll(/\{id:'([^']+)',profile:'([^']+)',label:/g)].map(m=>({id:m[1],profile:m[2]}));
assert.deepEqual(entries.map(x=>x.id),['awp01-v03','s12-v04','specter-midnight']);
for(const a of entries){const entry=WORKSHOP_CATALOG.find(x=>x.id===a.id);assert.ok(entry,'Missing catalog wall asset '+a.id);assert.ok(entry.profiles.some(p=>p.id===a.profile&&p.url));}
assert.ok(!racks.includes("ar01-code"));assert.ok(!racks.includes("smg05-code"));assert.ok(!racks.includes("operator03-code"));
assert.ok(inspector.includes('const direction=center.clone().sub(globalCenter)'));
assert.ok(inspector.includes('object.position.copy(item.origin).addScaledVector(item.delta,amount)'));
assert.ok(inspector.includes('selected.object.material=highlight.original'));
for(const text of [racks,inspector,workshop])assert.ok(!text.includes('new WebSocket('),'Workshop must not modify game network');
console.log('PASS: wall-mounted real GLBs, component inspector, single import, compact sidebar, multiplayer isolation.');