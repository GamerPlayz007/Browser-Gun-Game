import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const read=path=>readFileSync(new URL('../'+path,import.meta.url));
const source=read('static/awp01_v03_model.js').toString();
const game=read('static/game.js').toString();
const models=read('static/models.js').toString();
const workshop=read('static/workshop-library.js').toString();
const asset=read('static/assets/CROSSFIRE_AWP_ReferenceInspired_v03.glb');
const checksum=createHash('sha256').update(asset).digest('hex');
assert.equal(asset.byteLength,4682872);
assert.equal(checksum,'a227f177bc1d5398ec5919aaf537a8a29ab48a2c10b9c9c51b73b74366351b4b');
const view=new DataView(asset.buffer,asset.byteOffset,asset.byteLength);
assert.equal(view.getUint32(0,true),0x46546c67);
assert.equal(view.getUint32(8,true),asset.byteLength);
const jsonSize=view.getUint32(12,true);
const json=JSON.parse(asset.subarray(20,20+jsonSize).toString());
assert.equal(json.meshes.length,396);
assert.equal(json.materials.length,23);
assert.equal(json.images.length,59);
assert.match(source,/CROSSFIRE_AWP_ReferenceInspired_v03\.glb/);
assert.match(source,/MIN_PARTS=396/);
assert.match(source,/mergeGeometries\(items,false\)/);
assert.match(models,/id===3\)attachAWP01V03\(root\)/);
assert.match(models,/makeAWP01V03Scaffold\(model,magazine\)/);
assert.doesNotMatch(models,/id===3\?buildAetherGameVisuals|:buildAetherGameVisuals\(model,magazine,id,finish\)/);
assert.doesNotMatch(game,/AETHER-L7 LONGWATCH/);
assert.match(game,/AWP-01 V0\.3/);
assert.match(workshop,/awp01-v03','AWP-01 · v0\.3 ORIGINAL','production','In game'/);
assert.doesNotMatch(workshop,/entry\('l7-native'/);
console.log('AWP-01 v0.3 exact GLB, game renderer, catalog, and legacy removal PASS');
